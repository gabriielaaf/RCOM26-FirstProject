// Frame delimiters
#define FLAG 0x7E
#define ESC  0x7D

// Addresses
#define A_TX 0x03
#define A_RX 0x01

// Connection control
#define SET  0x03
#define UA   0x07
#define DISC 0x0B

// Information frames
#define I0 0x00
#define I1 0x40

// Positive acknowledgments
#define RR0 0x05
#define RR1 0x85

// Negative acknowledgments
#define REJ0 0x01
#define REJ1 0x81